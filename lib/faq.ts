/**
 * 자주묻는질문 콘텐츠 데이터 (/faq 페이지가 이 파일을 렌더링한다)
 *
 * ▣ 게시판이 아니라 "정적 문답"인 이유
 *    이전(대부업) 사이트에는 고객센터 아래에 공지사항 / Q&A / 자료실 등 게시판이 6개 있었다.
 *    관리자 페이지를 만들지 않기로 했으므로 운영이 불가능하고,
 *    · 고객이 글을 쓰는 Q&A는 답변이 안 달리면 오히려 방치된 인상을 준다
 *    · 공지사항은 갱신이 멈추면 폐업한 것처럼 보인다
 *    그래서 게시판은 전부 없애고, 회사가 직접 쓰고 코드로 수정하는 고정 문답만 남겼다.
 *    질문을 추가·수정하려면 이 파일의 FAQ_ITEMS 배열만 고치면 된다.
 *
 * ▣ 요금 비공개 정책 (중요)
 *    금액을 묻는 질문에는 절대 숫자를 쓰지 않는다.
 *    "차종과 대여 기간에 따라 달라져 전화로 안내드린다"는 답변 + 전화 링크로 통일한다.
 *    → 그런 항목은 `call: true` 로 표시하면 답변 끝에 전화 CTA가 자동으로 붙는다.
 *    (전화번호는 여기에 문자열로 적지 않는다. SITE.phone 한 곳에서만 관리한다.)
 *
 * ▣ TODO 표시 규칙
 *    고객사 확인이 필요한 항목은 `todo` 에 확인할 내용을 적어 두었고,
 *    화면에는 "확인 필요" 메모로 표시된다. 확인이 끝나면 답변을 확정하고 todo 를 지운다.
 */

